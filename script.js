let currentLang = localStorage.getItem('language') || 'es';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('language', lang);
  
  // Update all elements with data-translate
  document.querySelectorAll('[data-translate]').forEach(el => {
    const key = el.getAttribute('data-translate');
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });
  
  // Update all elements with data-placeholder
  document.querySelectorAll('[data-placeholder]').forEach(el => {
    const key = el.getAttribute('data-placeholder');
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });
  
  // Update language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.remove('active');
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    }
  });
  
  // Update HTML lang attribute
  document.documentElement.lang = lang;
}

// Initialize language on page load
function startSliderAutoplay() {
  const slides = Array.from(document.querySelectorAll('input[name="slider"]'));
  if (!slides.length) return;

  let currentIndex = slides.findIndex(slide => slide.checked);
  if (currentIndex === -1) currentIndex = 0;

  setInterval(() => {
    currentIndex = (currentIndex + 1) % slides.length;
    slides[currentIndex].checked = true;
  }, 4000);
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
  
  // Add event listeners to language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      setLanguage(lang);
    });
  });

  if (window.emailjs) {
    emailjs.init('vnDmphO2tGdkjDYgN');
  }

  const bookingForm = document.getElementById('bookingForm');
  if (bookingForm) {
    bookingForm.addEventListener('submit', (event) => {
      event.preventDefault();
      if (!window.emailjs) {
        alert('EmailJS no está cargado. Revisar la conexión al SDK.');
        return;
      }

      emailjs.sendForm('service_z02ylxk', 'template_vxxxuy7', bookingForm)
        .then(() => {
          alert('Reserva enviada correctamente.');
          bookingForm.reset();
        })
        .catch((error) => {
          console.error('EmailJS error:', error);
          alert('No se pudo enviar la reserva. Intenta de nuevo más tarde.');
        });
    });
  }

  startSliderAutoplay();
});

// Mobile menu toggle
const navToggle = document.getElementById('navToggle');
const siteNav = document.getElementById('siteNav');

if (navToggle && siteNav) {
  navToggle.addEventListener('click', () => {
    siteNav.classList.toggle('open');
    const expanded = siteNav.classList.contains('open');
    navToggle.setAttribute('aria-label', expanded ? currentLang === 'es' ? 'Cerrar menú' : 'Close menu' : currentLang === 'es' ? 'Abrir menú' : 'Open menu');
  });
}

// Smooth scroll links
const scrollLinks = document.querySelectorAll('a[href^="#"]');
scrollLinks.forEach((link) => {
  link.addEventListener('click', (event) => {
    const targetId = link.getAttribute('href');
    if (!targetId || targetId === '#') return;

    const target = document.querySelector(targetId);
    if (target) {
      event.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
      if (siteNav.classList.contains('open')) {
        siteNav.classList.remove('open');
        navToggle.setAttribute('aria-label', currentLang === 'es' ? 'Abrir menú' : 'Open menu');
      }
    }
  });
});
